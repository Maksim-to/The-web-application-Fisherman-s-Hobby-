# Функция для получения водоемов по виду рыбы
def get_waterbodies_for_fish(fish_name):
    """Возвращает список водоемов, где водится указанная рыба"""
    return fish_waterbody_relations.get(fish_name, [])

# Функция для получения рыб по водоему
def get_fish_for_waterbody(waterbody_name):
    """Возвращает список рыб, которые водятся в указанном водоеме"""
    fish_list = []
    for fish_name, waterbodies in fish_waterbody_relations.items():
        if waterbody_name in waterbodies:
            fish_list.append(fish_name)
    return fish_list